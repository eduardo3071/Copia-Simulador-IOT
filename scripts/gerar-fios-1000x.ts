// Routes the five wires of the economical 1000x version and stores them in packages/adapter-cad/src/suporte-1000x-fios.ts.
// Run after changing the layout or the terminals: npx tsx scripts/gerar-fios-1000x.ts
import { writeFileSync } from "node:fs";
import { routeWires1000x } from "../packages/adapter-cad/src/suporte-1000x-eletrica.ts";

const routes = routeWires1000x();
const body = routes.map((w) => `  ${JSON.stringify(w.spec.id)}: ${JSON.stringify(w.path)},`).join("\n");
writeFileSync(
  new URL("../packages/adapter-cad/src/suporte-1000x-fios.ts", import.meta.url),
  `// Generated by scripts/gerar-fios-1000x.ts: do not edit.\nexport const FIOS_1000X: Record<string, [number, number, number][]> = {\n${body}\n};\n`,
);
console.log(routes.length, "fios gravados em suporte-1000x-fios.ts");
