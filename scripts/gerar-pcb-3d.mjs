// Reads the circuit.json of each driver board and writes packages/adapter-cad/src/suporte-pcb.ts:
// pad positions, part positions and copper traces in board millimetres (origin at the board centre).
// Run after build-eletronica: node scripts/gerar-pcb-3d.mjs
import { readFileSync, writeFileSync } from "node:fs";

const r2 = (n) => Math.round(n * 100) / 100;
const data = {};
for (const [version, dir] of [["v1", "v1-pilha"], ["v2", "v2-fonte-dimmer"]]) {
  const j = JSON.parse(readFileSync(new URL(`../pacote-montagem/eletronica/${dir}/circuit.json`, import.meta.url), "utf8"));
  const comp = new Map(j.filter((e) => e.type === "source_component").map((e) => [e.source_component_id, e.name]));
  const port = new Map(j.filter((e) => e.type === "source_port").map((e) => [e.source_port_id, `${comp.get(e.source_component_id)}.${e.name}`]));
  const pcbPort = new Map(j.filter((e) => e.type === "pcb_port").map((e) => [e.pcb_port_id, e.source_port_id]));
  const board = j.find((e) => e.type === "pcb_board");
  const pads = {};
  for (const e of j) if (e.type === "pcb_plated_hole") pads[port.get(pcbPort.get(e.pcb_port_id))] = [r2(e.x), r2(e.y), r2(e.hole_diameter ?? e.outer_diameter ?? 1)];
  const parts = {};
  for (const e of j.filter((x) => x.type === "pcb_component")) parts[comp.get(e.source_component_id)] = { x: r2(e.center.x), y: r2(e.center.y), rot: e.rotation ?? 0 };
  const traces = j
    .filter((e) => e.type === "pcb_trace")
    .map((e) => {
      const wires = e.route.filter((p) => p.route_type === "wire");
      return { layer: (wires[0]?.layer ?? "top").startsWith("bottom") ? "bottom" : "top", width: r2(wires[0]?.width ?? 0.25), points: e.route.filter((p) => p.route_type === "wire" || p.route_type === "via").map((p) => [r2(p.x), r2(p.y)]) };
    });
  data[version] = { width: board.width, height: board.height, pads, parts, traces };
}
const body = `// Generated by scripts/gerar-pcb-3d.mjs from pacote-montagem/eletronica/*/circuit.json. Do not edit by hand.
// Board millimetres, origin at the board centre, +x right and +y up as in the Gerber files.
export interface PcbData {
  width: number;
  height: number;
  /** "REF.PIN" -> [x, y, hole diameter] */
  pads: Record<string, [number, number, number]>;
  parts: Record<string, { x: number; y: number; rot: number }>;
  traces: { layer: "top" | "bottom"; width: number; points: [number, number][] }[];
}
export const PCB: Record<"v1" | "v2", PcbData> = ${JSON.stringify(data)};
`;
writeFileSync(new URL("../packages/adapter-cad/src/suporte-pcb.ts", import.meta.url), body);
console.log("suporte-pcb.ts escrito:", Object.entries(data).map(([v, d]) => `${v}: ${Object.keys(d.pads).length} pads, ${d.traces.length} trilhas`).join("; "));
